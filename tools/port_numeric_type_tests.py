            out+=f'\n// {path}:{line}\npub fn {fn}()->Report{{\nlet mut r=Report::default();\n{code}\nr\n}}\n'
            native+=f'#[test]\n#[allow(non_snake_case)]\nfn {fn}(){{let r=blended_core::numeric_type_cases::{fn}();assert!(r.passed(),"{{:?}}",r.failures);assert_eq!(r.assertions,{sites});}}\n'
