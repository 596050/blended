def colors(body):
    code=numbers(comments(body)).replace('BLI_init_srgb_conversion()','color::init_srgb_conversion()')
    for orig,ty in COLOR_TYPES.items():
        code=re.sub(re.escape(orig)+r'\s+(\w+)\(([^;]+)\);',lambda m:f'let {m[1]}={ty}::new('+m[2]+');',code)
