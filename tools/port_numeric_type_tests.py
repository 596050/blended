def comments(s):
    # Mask comments while retaining strings/character literals and line positions.
    pattern=r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*.*?\*/|//[^\n]*'
    return re.sub(pattern,lambda m:re.sub(r'[^\n]',' ',m[0]) if m[0].startswith(('/',)) else m[0],s,flags=re.S)

def numbers(s):
    s=re.sub(r'\b(\d+(?:\.\d*)?(?:[eE][+-]?\d+)?)f\b',lambda m:(m[1] if '.' in m[1] or 'e' in m[1].lower() else m[1]+'.0')+'_f32',s)
    return re.sub(r'\b(\d+)u\b',r'\1_u32',s)

def vector_expr(s):
    s=numbers(s.strip()).replace('~','!')
    # Rewrite outermost constructors recursively before emitting Rust turbofish commas.
    pos=0
    while (match:=re.search(r'\b(float|double|uint|int)([234])\(',s[pos:])):
        start=pos+match.start();end=pos+match.end();i=end;depth=1
        while depth:
            if s[i]=='(':depth+=1
            elif s[i]==')':depth-=1
            i+=1
        ty={'float':'f32','double':'f64','uint':'u32','int':'i32'}[match[1]];n=match[2]
        value=f'v::construct::<{ty},{n}>(&['+', '.join('&('+vector_expr(x)+') as &dyn v::Components' for x in split_args(s[end:i-1]))+'])'
        s=s[:start]+value+s[i:];pos=start+len(value)
    s=re.sub(r'\b(\w+)\.([xyzw]{2,4})\(\)',lambda m:m[1]+'.swizzle(['+','.join(str('xyzw'.index(c)) for c in m[2])+'])',s)
    s=re.sub(r'\b(\w+)\.([xyzw])\b',lambda m:m[1]+'['+str('xyzw'.index(m[2]))+']',s)
    return s

def vectors(body):
    scalar_types={m[2]:{"float":"f32","double":"f64","int":"i32","uint":"u32"}[m[1]] for m in re.finditer(r"\b(float|double|uint|int)[234]\s+(\w+)",body)}
    code=comments(body)
    # Original pointer conversions copy the source elements; they do not alias the vector.
    code=code.replace('float array[3] = {1.0f, 2.0f, 3.0f};','let array = [1.0_f32, 2.0_f32, 3.0_f32];')
    code=code.replace('float array[1][3] = {{1.0f, 2.0f, 3.0f}};','let array = [[1.0_f32, 2.0_f32, 3.0_f32]];')
    code=code.replace('float (*ptr)[3] = array;','let ptr = &array[0];')
    for kind,ty in [('float','f32'),('double','f64'),('int','i32'),('uint','u32')]:
        for n in (2,3,4):
            typename=kind+str(n)
            pattern=r'(?:const\s+)?\b'+typename+r'\s+(\w+)\s*(\([^;]*\)|=\s*[^;]+);'
            def declaration(m):
                init=m[2].strip();init=typename+init if init.startswith('(') else init[1:].strip()
                return f'let mut {m[1]}:v::V<{ty},{n}> = {vector_expr(init)};'
            code=re.sub(pattern,declaration,code)
    code=re.sub(r'\bfloat (\w+) = ([^;]+);',lambda m:f'let {m[1]}:f32 = {numbers(m[2])};',code)
    # Evaluate RHS before write-back, including self-aliasing and repeated components.
    def assign(m):
        name,mask,op,rhs=m.groups();ix='['+','.join(str('xyzw'.index(c)) for c in mask)+']';rhs=vector_expr(rhs)
        if op=='=':return f'{name}.set_swizzle({ix},{rhs});'
        return f'{name}.set_swizzle({ix},{name}.swizzle({ix}) {op[:-1]} ({rhs} as {scalar_types[name]}));'
    code=re.sub(r'(?m)^\s*(\w+)\.([xyzw]{2,4})(?:\(\))?\s*(<<=|>>=|[+*/&|^\-]?=)(?!=)\s*([^;]+);',assign,code)
    # Non-call swizzle RHS denotes the original same-type view assignment.
    code=re.sub(r'\b(\w+)\.([xyzw]{2,4})\b(?!\s*\()',lambda m:m[1]+'.swizzle(['+','.join(str('xyzw'.index(c)) for c in m[2])+'])',code)
    code=vector_expr(code)
    for old,new in [('FLOAT_EQ','feq'),('EQ','eq')]:
        def assertion(a,new=new):
            args=split_args(a);macro=new
            if new=='eq' and not any(t in args[0] for t in ('.swizzle(', ' == ', ' != ')) and not (args[0].strip() in ('v01','v012','v0123')):
                # Field/subscript EQ values are all <= 2^53; f64 preserves both operands exactly.
                if re.search(r'\[[0-9]+\]$',args[0]):macro='numeq'
            return macro+'!(r, '+', '.join(args)+')'
        code=rewrite_calls(code,'EXPECT_'+old+'(',assertion)
    if 'EXPECT_' in code:raise ValueError('Untranslated vector assertion')
    return code

